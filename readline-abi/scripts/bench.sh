#!/usr/bin/env bash
# Build and run the readline-abi ABI benchmarks, then refresh BENCH.md.
#
#   readline-abi/scripts/bench.sh
#   BENCH_SAMPLES=41 readline-abi/scripts/bench.sh
#
# The example is compiled in release mode.  Each benchmark reports the median,
# minimum, and maximum over BENCH_SAMPLES (default 21) timed samples; the table
# is the checked-in baseline in readline-abi/BENCH.md.

set -euo pipefail

here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
crate=$(cd "$here/.." && pwd)
repo=$(cd "$crate/.." && pwd)
samples=${BENCH_SAMPLES:-21}

if ! [[ "$samples" =~ ^[1-9][0-9]*$ ]]; then
    echo "error: BENCH_SAMPLES must be a positive integer" >&2
    exit 1
fi

target_dir=$(
    cd "$repo"
    cargo metadata --format-version 1 --no-deps |
        python3 -c 'import json, sys; print(json.load(sys.stdin)["target_directory"])'
)

cd "$repo"
cargo build -p readline-abi --release --example abi_bench

library=""
for candidate in \
    "$target_dir/release/libreadline.so" \
    "$target_dir/release/libreadline.dylib" \
    "$target_dir/release/readline.dll"; do
    if [[ -f "$candidate" ]]; then
        library=$candidate
        break
    fi
done
if [[ -z "$library" ]]; then
    echo "error: built readline library not found under $target_dir/release" >&2
    exit 1
fi

binary="$target_dir/release/examples/abi_bench"
if [[ ! -x "$binary" ]]; then
    echo "error: benchmark binary not found: $binary" >&2
    exit 1
fi

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
export TMPDIR="$work"

run=(
    "$binary"
    --lib "$library"
    --samples "$samples"
    --tmp "$work/completion"
)
output=$("${run[@]}")

{
    echo "# readline-abi ABI benchmark baseline"
    echo
    echo "Generated by \`readline-abi/scripts/bench.sh\`. Re-run with:"
    echo
    echo '```sh'
    echo "BENCH_SAMPLES=$samples readline-abi/scripts/bench.sh"
    echo '```'
    echo
    echo "The harness loads the built shared object through \`dlopen\`/\`dlsym\`, so"
    echo "these are calls on the exported C ABI. Each row is the time per operation"
    echo "over \`BENCH_SAMPLES\` samples, after one untimed setup. \`ops/sample\` is"
    echo "the number of operations inside each timed sample (for example the 10k"
    echo "history row performs 10,000 \`add_history\` calls per sample). The delete"
    echo "rows remove the front half of a double-length line, so the measured"
    echo "delete has a tail to move instead of being an O(1) whole-line truncate."
    echo "Non-positive derived delete pairs are treated as timer noise and dropped."
    echo
    echo "- Environment: \`$(rustc --version)\`, \`$(uname -sm)\`"
    echo "- Library: \`${library#"$repo/"}\`"
    echo "- Samples: $samples"
    echo
    echo "Run command:"
    echo
    echo '```sh'
    echo "${binary#"$repo/"} --lib ${library#"$repo/"} --samples $samples"
    echo '```'
    echo
    echo "$output" | sed -n '/^| Benchmark/,$p'
    echo
    cat "$crate/benches/notes.md"
} > "$crate/BENCH.md"

echo "wrote $crate/BENCH.md"
echo
printf '%s\n' "$output"
